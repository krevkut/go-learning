// Генератор комплиментов
// Каждому разработчику время от времени нужна поддержка. Давайте напишем функцию, которая будет поднимать настроение пользователям нашего приложения.

// Вам необходимо реализовать функцию generateCompliment(name string) string, которая принимает имя человека и возвращает случайный комплимент из заранее предопределенного списка, подставляя переданное имя.

// Функция должна случайно выбирать один из трех следующих вариантов комплиментов:

// "Ты великолепен, [имя]!"
// "У тебя потрясающая улыбка, [имя]!"
// "Ты вдохновляешь, [имя]!"
// Для генерации случайного индекса используйте современный пакет стандартной библиотеки math/rand/v2.
// Как устроена проверка
// Тестирование вашего решения происходит прямо внутри кода с помощью вызова тестовых функций. Система передает различные имена, проверяет соответствие возвращаемого результата шаблонам, а также тестирует работу генератора случайных чисел.

// Вы можете изучить функцию main и структуру тестов в коде ниже (пока будет не все понятно, это нормально). Проверка построена на последовательном вызове, если какой-то тест возвращает false, выполнение прерывается с ошибкой. Для успешного прохождения задачи нужно, чтобы все тесты вернули true.

package main

import (
	"fmt"
	"math/rand/v2"
	"os"
)

// generateCompliment возвращает случайный комплимент для указанного имени.
func generateCompliment(name string) string {
	num := rand.IntN(3)
	switch num {
	case 0:
		return fmt.Sprintf("Ты великолепен, %s!", name)
	case 1:
		return fmt.Sprintf("У тебя потрясающая улыбка, %s!", name)
	default:
		return fmt.Sprintf("Ты вдохновляешь, %s!", name)
	}
}

// Функция main и все тесты будут скрыты от вас при проверке на сайте.
func main() {
	if !test1() || !test2() || !test3() || !test4() {
		os.Exit(1)
	}
	fmt.Println("Все тесты успешно пройдены!")
}

// Базовая проверка с обычным именем
func test1() bool {
	name := "Павел"
	res := generateCompliment(name)

	opt1 := "Ты великолепен, Павел!"
	opt2 := "У тебя потрясающая улыбка, Павел!"
	opt3 := "Ты вдохновляешь, Павел!"

	if res != opt1 && res != opt2 && res != opt3 {
		fmt.Fprintf(os.Stderr, "Тест 1: Для имени '%s' получен неожиданный ответ: '%s'\n", name, res)
		return false
	}
	return true
}

// На всякий случай, протестируем пустую строку вместо имени
func test2() bool {
	name := ""
	res := generateCompliment(name)

	opt1 := "Ты великолепен, !"
	opt2 := "У тебя потрясающая улыбка, !"
	opt3 := "Ты вдохновляешь, !"

	if res != opt1 && res != opt2 && res != opt3 {
		fmt.Fprintf(os.Stderr, "Тест 2: Для пустого имени получен неожиданный ответ: '%s'\n", res)
		return false
	}
	return true
}

// Проверка на пробелы и необычные символы в имени
func test3() bool {
	name := "Д'Артаньян Кек"
	res := generateCompliment(name)

	opt1 := "Ты великолепен, Д'Артаньян Кек!"
	opt2 := "У тебя потрясающая улыбка, Д'Артаньян Кек!"
	opt3 := "Ты вдохновляешь, Д'Артаньян Кек!"

	if res != opt1 && res != opt2 && res != opt3 {
		fmt.Fprintf(os.Stderr, "Тест 3: Для сложного имени получен неожиданный ответ: '%s'\n", res)
		return false
	}
	return true
}

// Проверяем, что комплименты действительно меняются, тестируем рандом
func test4() bool {
	name := "Тест"
	counts := make(map[string]struct{})

	// Делаем серию вызовов, чтобы убедиться в случайности выбора
	for range 1000 {
		res := generateCompliment(name)
		counts[res] = struct{}{}
	}

	if len(counts) < 2 {
		fmt.Fprintln(os.Stderr, "Тест 4: Функция возвращает один и тот же комплимент. Проверьте генерацию случайного индекса.")
		return false
	}
	return true
}
